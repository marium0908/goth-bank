import { jsPDF } from 'jspdf';
import type { BankAccount, BankTransaction } from '../types/banking';

export function formatCurrency(amount: number): string {
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(amount || 0);
}

export function formatDateTime(isoOrSql: string): string {
  if (!isoOrSql) return '—';
  const normalized = isoOrSql.includes('T') ? isoOrSql : isoOrSql.replace(' ', 'T') + 'Z';
  const date = new Date(normalized);
  if (Number.isNaN(date.getTime())) return isoOrSql;
  return new Intl.DateTimeFormat('en-US', {
    month: 'short',
    day: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date);
}

export function downloadTransactionReceiptPDF(tx: BankTransaction): void {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 595, 90, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text('GOTH BANK', 48, 46);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text('Official Transaction Receipt', 48, 66);
  doc.text(`Reference: ${tx.tx_ref}`, 370, 66);

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('Transaction Summary', 48, 130);

  const rows: Array<[string, string]> = [
    ['Transaction Reference', tx.tx_ref],
    ['Transaction Type', tx.tx_type],
    ['Status', tx.status],
    ['Date & Time', formatDateTime(tx.created_at)],
    ['Amount', formatCurrency(tx.amount)],
    ['Transaction Fee', formatCurrency(tx.fee)],
    ['Total Debited', formatCurrency(tx.amount + tx.fee)],
    ['Sender Account', tx.sender_account_number || 'External / Treasury'],
    ['Receiver Account', tx.receiver_account_number || 'External / Settlement'],
    ['Description', tx.description || '—'],
  ];

  let y = 160;
  doc.setFontSize(10.5);
  for (const [label, value] of rows) {
    doc.setDrawColor(226, 232, 240);
    doc.line(48, y + 10, 547, y + 10);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(71, 85, 105);
    doc.text(label, 48, y);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(15, 23, 42);
    doc.text(String(value).slice(0, 58), 230, y);
    y += 30;
  }

  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(
    'This receipt is electronically generated by Goth Bank for simulated banking verification.',
    48,
    y + 30
  );

  doc.save(`${tx.tx_ref}_Receipt.pdf`);
}

export function downloadAccountStatementCSV(
  account: BankAccount,
  transactions: BankTransaction[]
): void {
  const headers = [
    'Transaction Reference',
    'Date',
    'Type',
    'Sender Account',
    'Receiver Account',
    'Amount (USD)',
    'Fee (USD)',
    'Status',
    'Description',
  ];

  const escapeCsv = (val: unknown): string => {
    const str = String(val ?? '');
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const lines = [headers.join(',')];
  for (const tx of transactions) {
    lines.push(
      [
        tx.tx_ref,
        formatDateTime(tx.created_at),
        tx.tx_type,
        tx.sender_account_number || '',
        tx.receiver_account_number || '',
        tx.amount.toFixed(2),
        tx.fee.toFixed(2),
        tx.status,
        tx.description,
      ]
        .map(escapeCsv)
        .join(',')
    );
  }

  const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `Goth_Bank_Statement_${account.account_number}.csv`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function downloadAccountStatementPDF(
  account: BankAccount,
  transactions: BankTransaction[]
): void {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 595, 86, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('GOTH BANK — ACCOUNT STATEMENT', 40, 42);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(
    `Account: ${account.account_number} (${account.account_type})   |   Balance: ${formatCurrency(account.balance)}`,
    40,
    64
  );

  let y = 120;
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('Reference', 40, y);
  doc.text('Date', 165, y);
  doc.text('Type', 275, y);
  doc.text('Amount', 390, y);
  doc.text('Status', 485, y);
  doc.line(40, y + 6, 555, y + 6);
  y += 24;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);

  for (const tx of transactions.slice(0, 28)) {
    if (y > 780) {
      doc.addPage();
      y = 50;
    }
    doc.text(tx.tx_ref, 40, y);
    doc.text(formatDateTime(tx.created_at).slice(0, 18), 165, y);
    doc.text(tx.tx_type, 275, y);
    doc.text(formatCurrency(tx.amount), 390, y);
    doc.text(tx.status, 485, y);
    y += 22;
  }

  doc.save(`Goth_Bank_Statement_${account.account_number}.pdf`);
}
